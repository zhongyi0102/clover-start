using System;
using System.Collections.Generic;
using System.Reflection;
using System.Text;
using System.Threading;

namespace Clover
{
    /// <summary>
    /// 商店应用（UWP / MSIX）扫描：枚举 shell:AppsFolder。
    ///
    /// **为什么用 Shell.Application 晚绑定而不是手写 COM 接口**：
    /// 手写 IShellFolder / IEnumIDList / STRRET 三个接口约 150 行，
    /// 且 STRRET 的 Explicit 布局极易出错（实测尝试过，会抛
    /// "由于 Exception.ToString() 失败，因此无法打印异常字符串" 这种无从调试的异常）。
    ///
    /// Shell.Application 是 Windows 自带的 COM 组件（ProgID 稳定），
    /// 用 Type.GetTypeFromProgID + InvokeMember 晚绑定即可，零第三方库、零接口声明。
    /// 实测这台机器枚举 188 项，耗时约 150-400ms。
    ///
    /// **shell:AppsFolder 里混着两类东西**：
    ///   · 商店应用：Path 是 AUMID（如 `Bytedance.JianyingPro`，无盘符）
    ///   · 传统应用：Path 是文件路径（如 `C:\...\localsend_app.exe`）
    /// 后者已经由开始菜单/注册表覆盖，这里只取前者。
    ///
    /// 启动方式：explorer.exe shell:AppsFolder\&lt;AUMID&gt;
    /// </summary>
    static class StoreAppScanner
    {
        /// <summary>一条商店应用。</summary>
        public class Entry
        {
            public string DisplayName;
            /// <summary>AppUserModelID（去重键）。</summary>
            public string Aumid;
            /// <summary>启动路径：shell:AppsFolder\&lt;AUMID&gt;</summary>
            public string LaunchPath;

            /// <summary>
            /// 是不是**真正的商店应用**（MSIX / UWP 包）。
            ///
            /// 判定依据（不看名字、不看是否重复，只看 AUMID 格式）：
            ///   1. Shell 的 System.AppUserModel.PackageFamilyName 属性有值 → 真商店
            ///   2. 或 AUMID 形如 &lt;PackageFamilyName&gt;!&lt;AppId&gt;，且
            ///      PackageFamilyName 含 '_'（发布者哈希），如
            ///      Claude_pzs8sxrjxfjjc!Claude
            ///
            /// 反例（都不是商店应用，虽然也出现在 shell:AppsFolder 里）：
            ///   Chrome                              ← 字面量，Chrome 安装时注册的
            ///   Microsoft.Office.EXCEL.EXE.15       ← Office 的 AppsFolder 入口
            ///   Microsoft.Windows.ControlPanel      ← 系统 Shell 项
            /// </summary>
            public bool IsRealStore;

            /// <summary>包族名（真商店才有，可为空）。</summary>
            public string PackageFamilyName;
        }

        /// <summary>扫描统计。</summary>
        public class Stats
        {
            public int Enumerated;          // shell:AppsFolder 总项数
            public int SkippedTraditional;  // 传统应用（Path 是文件路径）
            public int SkippedNoName;       // 没显示名
            public int SkippedNoAumid;      // 拿不到 AUMID
            public int SkippedJunk;         // 卸载器/帮助文档之类
            public int SkippedUrl;          // URL 链接（http/https）
            public int SkippedClsid;        // CLSID 路径（{1AC14E77-...}\cmd.exe）
            public int SkippedAutoGen;      // 安装器生成项（Microsoft.AutoGenerated）
            public int StoreApps;           // 真商店应用数（加 ·商店 后缀）
            public int LegacyEntries;       // 非商店 AUMID 但无对应条目（收，不加后缀）

            public string Report()
            {
                return "商店: 枚举 " + Enumerated + " 项"
                     + " | 传统应用 " + SkippedTraditional
                     + " | URL " + SkippedUrl
                     + " | CLSID " + SkippedClsid
                     + " | 安装器生成 " + SkippedAutoGen
                     + " | 无名称 " + SkippedNoName
                     + " | 无AUMID " + SkippedNoAumid
                     + " | 非应用 " + SkippedJunk
                     + " | 商店应用 " + StoreApps;
            }
        }

        /// <summary>超时（毫秒）。枚举在个别机器上可能卡住，超时就放弃。</summary>
        const int TimeoutMs = 8000;

        /// <summary>
        /// 扫描商店应用。**必须在 STA 线程调用**（Shell COM 要求）。
        ///
        /// 内部会自己起一个 STA 线程并等待（带超时），
        /// 所以调用方不需要关心线程模型 —— 但不要从界面线程同步调用
        /// （会阻塞 UI 最多 8 秒）。
        /// </summary>
        public static List<Entry> Scan(Stats stats)
        {
            if (stats == null) stats = new Stats();
            List<Entry> result = null;

            Thread t = new Thread(delegate()
            {
                try { result = ScanCore(stats); }
                catch (Exception ex)
                {
                    Log.Hook(ex, "扫描商店应用");
                    result = new List<Entry>();
                }
            });
            t.IsBackground = true;
            try { t.SetApartmentState(ApartmentState.STA); } catch { }

            try
            {
                t.Start();
                if (!t.Join(TimeoutMs))
                {
                    Log.Warn("商店应用扫描超时（" + TimeoutMs + "ms），返回空列表");
                    return new List<Entry>();
                }
            }
            catch (Exception ex)
            {
                Log.Hook(ex, "启动商店扫描线程");
                return new List<Entry>();
            }

            List<Entry> list = result ?? new List<Entry>();
            Log.Info(stats.Report());
            return list;
        }

        /// <summary>在 STA 线程里实际干活。</summary>
        static List<Entry> ScanCore(Stats stats)
        {
            List<Entry> list = new List<Entry>();
            HashSet<string> seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            Type shellType = Type.GetTypeFromProgID("Shell.Application");
            if (shellType == null)
            {
                Log.Warn("找不到 Shell.Application（ProgID 不可用），跳过商店应用扫描");
                return list;
            }

            object shell = Activator.CreateInstance(shellType);
            if (shell == null) return list;

            object ns = shellType.InvokeMember("Namespace", BindingFlags.InvokeMethod, null, shell,
                new object[] { "shell:AppsFolder" });
            if (ns == null)
            {
                Log.Warn("Shell.Application.Namespace(\"shell:AppsFolder\") 返回 null");
                return list;
            }

            Type nsType = ns.GetType();
            object items = nsType.InvokeMember("Items", BindingFlags.InvokeMethod, null, ns, null);
            if (items == null) return list;

            Type itemsType = items.GetType();
            int count = 0;
            try { count = Convert.ToInt32(itemsType.InvokeMember("Count", BindingFlags.GetProperty, null, items, null)); }
            catch (Exception ex) { Log.Warn("读 AppsFolder 项数失败: " + ex.Message); return list; }

            stats.Enumerated = count;

            for (int i = 0; i < count; i++)
            {
                try
                {
                    object item = itemsType.InvokeMember("Item", BindingFlags.InvokeMethod, null, items,
                        new object[] { i });
                    if (item == null) continue;

                    Type it = item.GetType();
                    string name = "";
                    string path = "";
                    try { name = Convert.ToString(it.InvokeMember("Name", BindingFlags.GetProperty, null, item, null)); }
                    catch { }
                    try { path = Convert.ToString(it.InvokeMember("Path", BindingFlags.GetProperty, null, item, null)); }
                    catch { }

                    if (string.IsNullOrWhiteSpace(name)) { stats.SkippedNoName++; continue; }
                    name = name.Trim();
                    path = (path ?? "").Trim();

                    // ---- 过滤 1：URL 链接 ----
                    //
                    // shell:AppsFolder 里混着「官网」「帮助文档」这类 URL 项，
                    // Path 就是 http:// 或 https:// 开头的网址。
                    // 它们不是应用，点了会开浏览器。
                    // 忽略大小写（实测有 HTTP:// 的情况）。
                    if (path.StartsWith("http://", StringComparison.OrdinalIgnoreCase)
                        || path.StartsWith("https://", StringComparison.OrdinalIgnoreCase))
                    {
                        stats.SkippedUrl++;
                        continue;
                    }

                    // ---- 过滤 2：CLSID 路径 ----
                    //
                    // 形如 {1AC14E77-02E7-4E5D-B744-2EB1AE5198B7}\cmd.exe
                    // 这是 Shell 的「已知文件夹 CLSID」+ 相对路径，
                    // 指向系统工具（cmd / regedit / msconfig / services.msc …）。
                    //
                    // 为什么排除：这些工具在开始菜单里已经有了（开始菜单扫描会覆盖），
                    // 再收一遍就是重复条目。
                    //
                    // 注意：这里判断的是**原始 Shell Path**（不是格式化显示串）——
                    // 实测 Path 属性返回的就是这个原始形式，可以安全按 '{' 开头判断。
                    if (path.StartsWith("{"))
                    {
                        stats.SkippedClsid++;
                        continue;
                    }

                    // ---- 过滤 3：安装器生成项 ----
                    //
                    // 形如 Microsoft.AutoGenerated.{0787AC3B-...}
                    // 这是安装器（Anaconda / Git / MySQL / Python / HP 等）
                    // 往开始菜单注册的快捷入口，不是商店应用。
                    //
                    // 忽略大小写（实测有 microsoft.autogenerated 的情况）。
                    if (path.IndexOf("Microsoft.AutoGenerated", StringComparison.OrdinalIgnoreCase) >= 0)
                    {
                        stats.SkippedAutoGen++;
                        continue;
                    }

                    // ---- 区分商店应用 vs 传统应用 ----
                    //
                    // 传统应用的 Path 是文件路径（含盘符，如 C:\...\a.exe）；
                    // 商店应用的 Path 是 AUMID（如 Bytedance.JianyingPro）。
                    if (LooksLikeFilePath(path))
                    {
                        stats.SkippedTraditional++;
                        continue;
                    }

                    if (string.IsNullOrWhiteSpace(path))
                    {
                        stats.SkippedNoAumid++;
                        continue;
                    }

                    // ---- 排除非应用条目 ----
                    //
                    // shell:AppsFolder 里还混着「卸载 xxx」「xxx 帮助」这类项。
                    // 复用 PortableScanner 的 junk 规则（只传名字，没路径）。
                    if (PortableScanner.IsJunk(name + ".exe", null))
                    {
                        stats.SkippedJunk++;
                        continue;
                    }
                    if (name.StartsWith("Uninstall ", StringComparison.OrdinalIgnoreCase))
                    {
                        stats.SkippedJunk++;
                        continue;
                    }
                    // 帮助文档 / 手册
                    string lower = name.ToLowerInvariant();
                    if (lower.EndsWith(" help") || lower.EndsWith(" manual")
                        || lower.EndsWith(" manuals") || lower.IndexOf("documentation") >= 0)
                    {
                        stats.SkippedJunk++;
                        continue;
                    }

                    // ---- 去重（AUMID 唯一）----
                    if (!seen.Add(path)) continue;

                    Entry e = new Entry();
                    e.DisplayName = name;
                    e.Aumid = path;
                    e.LaunchPath = AppPaths.FromAumid(path);

                    // ---- 判定「真商店应用」----
                    //
                    // 只按 AUMID 格式判断，不看名字、不看是否重复：
                    //   1. 先尝试读 Shell 的 PackageFamilyName 属性（最可靠）
                    //   2. 读不到时按格式推断：<PackageFamilyName>!<AppId>，
                    //      且 PackageFamilyName 含 '_'（发布者哈希）
                    string pfn = TryGetPackageFamilyName(it, item);
                    e.PackageFamilyName = pfn ?? "";
                    e.IsRealStore = !string.IsNullOrEmpty(pfn) || LooksLikePackageAumid(path);

                    list.Add(e);
                }
                catch (Exception ex)
                {
                    // 单项失败不影响整体
                    Log.Warn("读 AppsFolder 第 " + i + " 项失败: " + ex.Message);
                }
            }

            stats.StoreApps = 0;
            stats.LegacyEntries = 0;
            foreach (Entry e in list) { if (e.IsRealStore) stats.StoreApps++; else stats.LegacyEntries++; }

            // 按名称排序，保证结果确定性（不依赖 COM 枚举顺序）
            list.Sort(delegate(Entry a, Entry b)
            {
                int c = string.Compare(Pinyin.SortKey(a.DisplayName), Pinyin.SortKey(b.DisplayName),
                    StringComparison.Ordinal);
                if (c != 0) return c;
                return string.Compare(a.Aumid, b.Aumid, StringComparison.OrdinalIgnoreCase);
            });

            return list;
        }

        /// <summary>
        /// 判断 Shell 的 Path 是不是文件系统路径。
        ///
        /// 判定依据：含盘符（`X:\`）或 UNC 前缀（`\\`）。
        /// 商店应用的 AUMID 形如 `Bytedance.JianyingPro` / `Microsoft.WindowsCalculator_8wekyb3d8bbwe!App`，
        /// 不含盘符。
        /// </summary>
        /// <summary>
        /// 读 Shell 项的 System.AppUserModel.PackageFamilyName 属性。
        ///
        /// 这是判定「真商店应用」最可靠的方式：只有 MSIX/UWP 包才有这个属性。
        /// 读不到（传统软件、系统 Shell 项）返回 null。
        ///
        /// 实测结果：
        ///   Claude_pzs8sxrjxfjjc!Claude              → "Claude_pzs8sxrjxfjjc"
        ///   MSTeams_8wekyb3d8bbwe!MSTeams            → "MSTeams_8wekyb3d8bbwe"
        ///   Chrome                                   → ""（空，不是商店应用）
        ///   Microsoft.Office.EXCEL.EXE.15            → ""（空）
        ///   Microsoft.Windows.ControlPanel           → ""（空）
        /// </summary>
        static string TryGetPackageFamilyName(Type itemType, object item)
        {
            try
            {
                object v = itemType.InvokeMember("ExtendedProperty", BindingFlags.InvokeMethod,
                    null, item, new object[] { "System.AppUserModel.PackageFamilyName" });
                string s = v as string;
                return string.IsNullOrWhiteSpace(s) ? null : s.Trim();
            }
            catch { return null; }
        }

        /// <summary>
        /// 按 AUMID 格式推断是不是商店应用（读不到 PackageFamilyName 时的兜底）。
        ///
        /// 真商店的 AUMID 形如 &lt;PackageFamilyName&gt;!&lt;AppId&gt;，
        /// 而 PackageFamilyName 一定是 &lt;Name&gt;_&lt;13位发布者哈希&gt;，
        /// 例如 Microsoft.WindowsCalculator_8wekyb3d8bbwe。
        ///
        /// 反例：
        ///   Chrome                          ← 无 !，无下划线哈希
        ///   Microsoft.Office.EXCEL.EXE.15   ← 无 !
        ///   Microsoft.Windows.ControlPanel  ← 无 !
        ///   Valve.Steam.Client              ← 无 !
        /// </summary>
        public static bool LooksLikePackageAumid(string aumid)
        {
            try
            {
                if (string.IsNullOrWhiteSpace(aumid)) return false;
                int bang = aumid.IndexOf('!');
                if (bang <= 0) return false;                    // 必须有 !
                if (bang >= aumid.Length - 1) return false;     // ! 后面要有 AppId

                string family = aumid.Substring(0, bang);
                int us = family.LastIndexOf('_');
                if (us <= 0) return false;                      // 必须有下划线
                if (us >= family.Length - 1) return false;

                // 下划线后应该是发布者哈希（13 位字母数字）
                string hash = family.Substring(us + 1);
                if (hash.Length < 8) return false;
                foreach (char c in hash)
                {
                    if (!char.IsLetterOrDigit(c)) return false;
                }
                return true;
            }
            catch { return false; }
        }

        static bool LooksLikeFilePath(string path)
        {
            try
            {
                if (string.IsNullOrWhiteSpace(path)) return false;
                string p = path.Trim();
                if (p.StartsWith("\\\\")) return true;                     // UNC
                if (p.Length >= 3 && char.IsLetter(p[0]) && p[1] == ':' && (p[2] == '\\' || p[2] == '/'))
                    return true;                                            // X:\
                return false;
            }
            catch { return false; }
        }

        /// <summary>输出文件路径。</summary>
        public static string PathOf(string baseDir)
        {
            return System.IO.Path.Combine(baseDir, "config", "store-apps.json");
        }

        /// <summary>把扫描结果写成 store-apps.json。</summary>
        public static bool Save(string baseDir, List<Entry> entries, Stats stats)
        {
            try
            {
                List<object> arr = new List<object>();
                foreach (Entry e in entries)
                {
                    Dictionary<string, object> m = new Dictionary<string, object>();
                    m["name"] = e.DisplayName;
                    m["aumid"] = e.Aumid;
                    m["launchPath"] = e.LaunchPath;
                    m["isRealStore"] = e.IsRealStore;
                    if (!string.IsNullOrEmpty(e.PackageFamilyName))
                        m["packageFamilyName"] = e.PackageFamilyName;
                    arr.Add(m);
                }

                Dictionary<string, object> root = new Dictionary<string, object>();
                root["updated"] = DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss");
                root["stats"] = stats == null ? "" : stats.Report();
                root["apps"] = arr;

                System.Web.Script.Serialization.JavaScriptSerializer ser =
                    new System.Web.Script.Serialization.JavaScriptSerializer();
                ser.MaxJsonLength = int.MaxValue;
                JsonIO.WriteAtomic(PathOf(baseDir), ser.Serialize(root));
                return true;
            }
            catch (Exception ex)
            {
                Log.Hook(ex, "写 store-apps.json");
                return false;
            }
        }
    }
